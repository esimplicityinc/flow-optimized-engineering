import type { ReactNode } from 'react';
import { useState, useCallback, useMemo } from 'react';
import { questions, principles, type PrincipleKey } from './assessmentData';
import styles from './styles.module.css';

interface Answers {
  [questionId: string]: number;
}

interface PrincipleScore {
  key: PrincipleKey;
  label: string;
  cssVar: string;
  average: number;
  lowest: number;
  answers: number[];
}

interface AnalysisResult {
  overall: number;
  lowestConsistent: number;
  principleScores: PrincipleScore[];
  patterns: string[];
  concerns: string[];
}

function analyze(answers: Answers): AnalysisResult {
  const principleScores: PrincipleScore[] = principles.map((p) => {
    const pQuestions = questions.filter((q) => q.principle === p.key);
    const vals = pQuestions.map((q) => answers[q.id] ?? 0);
    const avg = vals.reduce((s, v) => s + v, 0) / vals.length;
    const low = Math.min(...vals);
    return {
      key: p.key,
      label: p.label,
      cssVar: p.cssVar,
      average: Math.round(avg * 10) / 10,
      lowest: low,
      answers: vals,
    };
  });

  const allVals = Object.values(answers);
  const overall = Math.round((allVals.reduce((s, v) => s + v, 0) / allVals.length) * 10) / 10;
  const lowestConsistent = Math.min(...principleScores.map((p) => p.lowest));

  const patterns: string[] = [];
  const concerns: string[] = [];

  // Healthy patterns
  const avgScores = principleScores.map((p) => p.average);
  if (avgScores.every((a) => a >= 1 && a <= 2.5)) {
    patterns.push('Mostly Level 1-2 with room to grow -- common and healthy starting point.');
  }
  if (avgScores.every((a) => a >= 2 && a <= 3.5)) {
    patterns.push('Level 2-3 range indicates solid FOE implementation with mature practices.');
  }
  if (avgScores.every((a) => a >= 3)) {
    patterns.push('Consistent Level 3+ across all principles -- strong FOE implementation.');
  }

  // Check for gaps between principles
  const maxAvg = Math.max(...avgScores);
  const minAvg = Math.min(...avgScores);
  if (maxAvg - minAvg >= 1.5) {
    const strongest = principleScores.find((p) => p.average === maxAvg)!;
    const weakest = principleScores.find((p) => p.average === minAvg)!;
    patterns.push(
      `${strongest.label} (${strongest.average}) is stronger than ${weakest.label} (${weakest.average}). The gap suggests a clear improvement target.`
    );
  }

  // Concerning patterns
  const zeroAnswers = allVals.filter((v) => v === 0);
  if (zeroAnswers.length > 0) {
    concerns.push(
      `${zeroAnswers.length} answer(s) at Level 0 indicate immediate risk areas that need attention.`
    );
  }
  if (avgScores.every((a) => a >= 3.5)) {
    concerns.push(
      'All scores at Level 3.5+ is unusual. Verify these answers reflect behavior under pressure, not aspirational state.'
    );
  }

  const spread = Math.max(...allVals) - Math.min(...allVals);
  if (spread >= 3) {
    concerns.push(
      `Wide spread (Level ${Math.min(...allVals)} to Level ${Math.max(...allVals)}) within your answers. Wildly inconsistent maturity across areas may indicate alignment problems.`
    );
  }

  return { overall, lowestConsistent, principleScores, patterns, concerns };
}

function formatResultsAsMarkdown(result: AnalysisResult, answers: Answers): string {
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let md = `# FOE Maturity Self-Assessment Results\n`;
  md += `Date: ${date}\n\n`;
  md += `## Summary\n`;
  md += `- **Overall Average**: ${result.overall} / 4\n`;
  md += `- **Lowest Consistent Level**: ${result.lowestConsistent}\n\n`;

  md += `## Scores by Principle\n\n`;
  for (const ps of result.principleScores) {
    md += `### ${ps.label}\n`;
    md += `- Average: ${ps.average} / 4\n`;
    md += `- Lowest: ${ps.lowest}\n\n`;
  }

  md += `## Individual Answers\n\n`;
  md += `| # | Question | Level |\n`;
  md += `|---|----------|-------|\n`;
  for (const q of questions) {
    md += `| ${q.number} | ${q.text} | ${answers[q.id] ?? '-'} |\n`;
  }

  if (result.patterns.length > 0) {
    md += `\n## Healthy Patterns\n\n`;
    for (const p of result.patterns) {
      md += `- ${p}\n`;
    }
  }

  if (result.concerns.length > 0) {
    md += `\n## Concerns\n\n`;
    for (const c of result.concerns) {
      md += `- ${c}\n`;
    }
  }

  md += `\n---\n`;
  md += `Generated by FOE Maturity Self-Assessment\n`;
  md += `https://esimplicityinc.github.io/flow-optimized-engineering/docs/maturity-model/self-assessment\n`;

  return md;
}

function ProgressBar({ value, max, color }: { value: number; max: number; color: string }) {
  const pct = (value / max) * 100;
  return (
    <div className={styles.progressBarTrack}>
      <div
        className={styles.progressBarFill}
        style={{ width: `${pct}%`, backgroundColor: color }}
      />
    </div>
  );
}

function ResultsPanel({
  result,
  answers,
  onReset,
}: {
  result: AnalysisResult;
  answers: Answers;
  onReset: () => void;
}) {
  const [copied, setCopied] = useState(false);

  const handleCopy = useCallback(() => {
    const md = formatResultsAsMarkdown(result, answers);
    navigator.clipboard.writeText(md).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  }, [result, answers]);

  const handleDownload = useCallback(() => {
    const md = formatResultsAsMarkdown(result, answers);
    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `foe-assessment-${new Date().toISOString().split('T')[0]}.md`;
    a.click();
    URL.revokeObjectURL(url);
  }, [result, answers]);

  const levelLabel = (level: number): string => {
    if (level >= 3.5) return 'Elite';
    if (level >= 2.5) return 'Strong';
    if (level >= 1.5) return 'Developing';
    if (level >= 0.5) return 'Beginning';
    return 'Critical';
  };

  return (
    <div className={styles.resultsPanel}>
      <h2 className={styles.resultsTitle}>Assessment Results</h2>

      <div className={styles.overallScore}>
        <div className={styles.overallScoreNumber}>{result.overall}</div>
        <div className={styles.overallScoreContext}>
          <span className={styles.overallScoreLabel}>Overall Average (out of 4)</span>
          <span className={styles.overallScoreLevel}>{levelLabel(result.overall)}</span>
        </div>
      </div>

      <div className={styles.lowestLevel}>
        Your lowest consistent level is <strong>Level {result.lowestConsistent}</strong>.
        This is where your organization operates under strain.
      </div>

      <div className={styles.principleScores}>
        {result.principleScores.map((ps) => (
          <div key={ps.key} className={styles.principleScoreCard}>
            <div className={styles.principleScoreHeader}>
              <span
                className={styles.principleDot}
                style={{ backgroundColor: ps.cssVar }}
              />
              <span className={styles.principleScoreLabel}>{ps.label}</span>
              <span className={styles.principleScoreValue}>{ps.average}</span>
            </div>
            <ProgressBar value={ps.average} max={4} color={ps.cssVar} />
            <div className={styles.principleScoreMeta}>
              Lowest: Level {ps.lowest}
            </div>
          </div>
        ))}
      </div>

      {result.patterns.length > 0 && (
        <div className={styles.analysisSection}>
          <h3 className={styles.analysisSectionTitle}>Healthy Patterns</h3>
          <ul className={styles.analysisList}>
            {result.patterns.map((p, i) => (
              <li key={i}>{p}</li>
            ))}
          </ul>
        </div>
      )}

      {result.concerns.length > 0 && (
        <div className={`${styles.analysisSection} ${styles.analysisConcerns}`}>
          <h3 className={styles.analysisSectionTitle}>Concerns</h3>
          <ul className={styles.analysisList}>
            {result.concerns.map((c, i) => (
              <li key={i}>{c}</li>
            ))}
          </ul>
        </div>
      )}

      <div className={styles.resultsActions}>
        <button
          className={styles.actionButton}
          onClick={handleCopy}
          type="button"
        >
          {copied ? 'Copied!' : 'Copy as Markdown'}
        </button>
        <button
          className={styles.actionButton}
          onClick={handleDownload}
          type="button"
        >
          Download Results
        </button>
        <button
          className={`${styles.actionButton} ${styles.actionButtonSecondary}`}
          onClick={onReset}
          type="button"
        >
          Retake Assessment
        </button>
      </div>
    </div>
  );
}

export default function SelfAssessment(): ReactNode {
  const [answers, setAnswers] = useState<Answers>({});
  const [submitted, setSubmitted] = useState(false);

  const totalQuestions = questions.length;
  const answeredCount = Object.keys(answers).length;
  const allAnswered = answeredCount === totalQuestions;

  const handleSelect = useCallback((questionId: string, level: number) => {
    setAnswers((prev) => ({ ...prev, [questionId]: level }));
  }, []);

  const handleSubmit = useCallback(() => {
    if (allAnswered) {
      setSubmitted(true);
      // Scroll to top of results
      setTimeout(() => {
        document.getElementById('assessment-results')?.scrollIntoView({ behavior: 'smooth' });
      }, 100);
    }
  }, [allAnswered]);

  const handleReset = useCallback(() => {
    setAnswers({});
    setSubmitted(false);
    setTimeout(() => {
      document.getElementById('assessment-start')?.scrollIntoView({ behavior: 'smooth' });
    }, 100);
  }, []);

  const result = useMemo(() => (submitted ? analyze(answers) : null), [submitted, answers]);

  // Group questions by principle
  const sections = useMemo(() => {
    return principles.map((p) => ({
      ...p,
      questions: questions.filter((q) => q.principle === p.key),
    }));
  }, []);

  if (submitted && result) {
    return (
      <div id="assessment-results">
        <ResultsPanel result={result} answers={answers} onReset={handleReset} />
      </div>
    );
  }

  return (
    <div id="assessment-start" className={styles.assessment}>
      <div className={styles.progressHeader}>
        <div className={styles.progressText}>
          {answeredCount} of {totalQuestions} questions answered
        </div>
        <ProgressBar
          value={answeredCount}
          max={totalQuestions}
          color="var(--ifm-color-primary)"
        />
      </div>

      {sections.map((section) => (
        <div key={section.key} className={styles.section}>
          <h2 className={styles.sectionTitle}>
            <span
              className={styles.sectionDot}
              style={{ backgroundColor: section.cssVar }}
            />
            {section.label} Assessment
          </h2>

          {section.questions.map((q) => {
            const selected = answers[q.id];
            return (
              <div key={q.id} className={styles.questionCard}>
                <h3 className={styles.questionTitle}>
                  <span className={styles.questionNumber}>Q{q.number}</span>
                  {q.text}
                </h3>

                <div className={styles.levelOptions}>
                  {q.levels.map((opt) => {
                    const isSelected = selected === opt.level;
                    return (
                      <button
                        key={opt.level}
                        type="button"
                        className={`${styles.levelOption} ${isSelected ? styles.levelOptionSelected : ''}`}
                        onClick={() => handleSelect(q.id, opt.level)}
                        aria-pressed={isSelected}
                        style={
                          isSelected
                            ? { borderColor: section.cssVar, backgroundColor: `color-mix(in srgb, ${section.cssVar} 8%, transparent)` }
                            : undefined
                        }
                      >
                        <span
                          className={styles.levelBadge}
                          style={isSelected ? { backgroundColor: section.cssVar, color: '#fff' } : undefined}
                        >
                          {opt.level}
                        </span>
                        <span className={styles.levelDescription}>{opt.description}</span>
                      </button>
                    );
                  })}
                </div>
              </div>
            );
          })}
        </div>
      ))}

      <div className={styles.submitArea}>
        <button
          type="button"
          className={`${styles.submitButton} ${!allAnswered ? styles.submitButtonDisabled : ''}`}
          onClick={handleSubmit}
          disabled={!allAnswered}
        >
          {allAnswered ? 'See Results' : `Answer all questions (${answeredCount}/${totalQuestions})`}
        </button>
      </div>
    </div>
  );
}
